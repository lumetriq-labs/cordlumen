// A 37 x 23 test pattern; expected values from Pillow 13 Image.resize(..., Image.BILINEAR).
function pattern(): ImageData {
  const W = 37, H = 23;
  const data = new Uint8ClampedArray(W * H * 4);
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      const i = (y * W + x) * 4;
      data[i] = (x * 7 + y * 3) % 256;
      data[i + 1] = (x * x + y * 11) % 256;
      data[i + 2] = (x * y * 5) % 256;
      data[i + 3] = 255;
    }
  }
  return { width: W, height: H, data, colorSpace: "srgb" } as ImageData;
}

